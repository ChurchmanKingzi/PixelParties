def star_pixels(frame_grid, dy):
    """Sternpixel eines Original-Frames, relativ zur Sternmitte (ohne Bob)."""
    pts = []
    for y in range(FH):
        for x in range(FW):
            ch = frame_grid[y][x]
            if ch in 'XU' and x >= 20 and y <= 17:
                pts.append((x - STAR_CENTER[0], y - dy - STAR_CENTER[1], ch))
    return pts

def build_up(frame_grid, f):
    g = mirror(frame_grid)
    dy = DY[f]
    # Sternpixel liegen im gespiegelten Bild links vom Kopf; nicht übermalen
    stars = {(35 - x - 0, y) for y in range(FH) for x in range(FW)
             if frame_grid[y][x] in 'XU' and x >= 20 and y <= 17}
    blit(g, UP_OVERLAY, 0, dy, skip=lambda x, y: (x, y) in stars)
    return g

