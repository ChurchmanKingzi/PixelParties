"""
Vier-Richtungen-Sheet für „Cool Rescuer Monia“ im Stil der Hero-Animationen.

Zeile „down“ ist das unveränderte Original (data/hero-animations/cool-rescuer-monia.png,
32 Frames à 36×37). Die anderen drei Richtungen werden daraus abgeleitet:

  up    – Original horizontal gespiegelt, darüber ein handgezeichnetes Overlay
          (Hinterkopf, Jackenrücken, Jetpack). Tolle, Stern, Düsen, Flammen und
          Beinpendeln kommen so Frame für Frame aus dem Original.
  right – handgezeichnete Ebenen (Kopf, Torso, Arm, Beine, Düse); Flamme pro Frame
          aus dem Original kopiert; Schwebe-Bob und Beinpendeln wie im Original.
  left  – gespiegelte Ebenen von „right“ mit erhobenem Arm (wie im Original die
          linke Faust) und dem pulsierenden Stern an der Haarspange.

Aufruf:  python3 scripts/charsets/monia_directions.py [--preview DIR]
Ausgabe: data/hero-charsets/cool-rescuer-monia.png   (1152×148: up, right, down, left)
"""
