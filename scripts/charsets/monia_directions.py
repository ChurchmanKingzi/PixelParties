# Schwebe-Bob je Frame (aus dem Original gemessen, 16er-Zyklus, zweimal)
DY = [0, 0, 0, -1, -1, -1, -2, -2, -2, -2, -2, -1, -1, -1, 0, 0] * 2
# Beinpendeln: ihr rechtes Bein (Betrachter links) in Frames 2–10, ihr linkes in 11–14
RIGHT_LEG_KICK = {f for f in range(NF) if 2 <= f % 16 <= 10}
LEFT_LEG_KICK = {f for f in range(NF) if 11 <= f % 16 <= 14}
STAR_CENTER = (23, 13)     # Sternmitte im Original (Frame-0-Koordinaten)

def layer(text):
    rows = text.strip('\n').split('\n')
    out = [['.'] * FW for _ in range(FH)]
    for y, r in enumerate(rows):
        assert len(r) == FW, f'Zeile {y} hat {len(r)} Zeichen: {r!r}'
        out[y] = list(r)
    assert len(rows) <= FH
    return out

def new_grid():
    return [['.'] * FW for _ in range(FH)]

def blit(dst, src, dx=0, dy=0, skip=None):
    for y in range(FH):
        for x in range(FW):
            ch = src[y][x]
            if ch == '.':
                continue
            tx, ty = x + dx, y + dy
            if 0 <= tx < FW and 0 <= ty < FH:
                if skip and skip(tx, ty):
                    continue
                dst[ty][tx] = ch

def mirror(g):
    return [row[::-1] for row in g]

def grid_from_image(img):
    px = img.load()
    g = new_grid()
    for y in range(FH):
        for x in range(FW):
            c = px[x, y]
            if c[3]:
                g[y][x] = SYM[c[:3]]
    return g

def render(g):
    im = Image.new('RGBA', (FW, FH), (0, 0, 0, 0))
    px = im.load()
    for y in range(FH):
        for x in range(FW):
            ch = g[y][x]
            if ch != '.':
                px[x, y] = PAL[ch] + (255,)
    return im

