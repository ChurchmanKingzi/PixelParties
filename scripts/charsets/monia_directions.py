LEFT_STAR_CENTER = (16, 12)

def copy_flame(dst, frame_grid, x0, x1, dx):
    for y in range(FH):
        for x in range(x0, x1 + 1):
            ch = frame_grid[y][x]
            if ch != '.' and PAL[ch] in FLAME and 0 <= x + dx < FW:
                dst[y][x + dx] = ch

def build_side(frame_grid, f, facing):
    g = new_grid()
    dy = DY[f]
    if facing == 'right':
        copy_flame(g, frame_grid, 3, 12, +4)            # linke Original-Flamme unter die Düse
        blit(g, R_THRUSTER, 0, dy)
        far_dx = 1 if f in LEFT_LEG_KICK else 0         # fernes Bein = ihr linkes
        near_dx = 1 if f in RIGHT_LEG_KICK else 0       # nahes Bein = ihr rechtes
        blit(g, R_LEG_FAR, far_dx, dy)
        blit(g, R_TORSO, 0, dy)
        blit(g, R_LEG_NEAR, near_dx, dy)
        blit(g, R_ARM, 0, dy)
        blit(g, R_HEAD, 0, dy)
    else:
        copy_flame(g, frame_grid, 23, 32, -4)           # rechte Original-Flamme
        blit(g, L_THRUSTER, 0, dy)
        far_dx = -1 if f in RIGHT_LEG_KICK else 0       # fernes Bein = ihr rechtes
        near_dx = -1 if f in LEFT_LEG_KICK else 0       # nahes Bein = ihr linkes
        blit(g, L_LEG_FAR, far_dx, dy)
        blit(g, L_TORSO, 0, dy)
        blit(g, L_LEG_NEAR, near_dx, dy)
        blit(g, L_HEAD, 0, dy)
        blit(g, L_ARM, 0, dy)
        for rx, ry, ch in star_pixels(frame_grid, dy):
            x, y = LEFT_STAR_CENTER[0] + rx, LEFT_STAR_CENTER[1] + ry + dy
            if 0 <= x < FW and 0 <= y < FH:
                g[y][x] = ch
    return g

ORDER = ['up', 'right', 'down', 'left']

def build_sheet():
    src = Image.open(SRC).convert('RGBA')
    frames = [src.crop((i * FW, 0, (i + 1) * FW, FH)) for i in range(NF)]
    grids = [grid_from_image(fr) for fr in frames]
    sheet = Image.new('RGBA', (FW * NF, FH * 4), (0, 0, 0, 0))
    rows = {}
    for r, d in enumerate(ORDER):
        rows[d] = []
        for f in range(NF):
            if d == 'down':
                im = frames[f]
            elif d == 'up':
                im = render(build_up(grids[f], f))
            else:
                im = render(build_side(grids[f], f, d))
            rows[d].append(im)
            sheet.paste(im, (f * FW, r * FH))
    return sheet, rows

def main():
    preview_dir = None
    if '--preview' in sys.argv:
        preview_dir = sys.argv[sys.argv.index('--preview') + 1]
    os.makedirs(OUT_DIR, exist_ok=True)
    sheet, rows = build_sheet()
    sheet.save(os.path.join(OUT_DIR, 'cool-rescuer-monia.png'))
    if preview_dir:
        os.makedirs(preview_dir, exist_ok=True)
        S = 8
        GREEN = (32, 156, 0, 255)
        # Frame 0 aller Richtungen nebeneinander
        big = Image.new('RGBA', (4 * (FW * S + S) + S, FH * S + 2 * S), GREEN)
        for i, d in enumerate(ORDER):
            im = rows[d][0].resize((FW * S, FH * S), Image.NEAREST)
            big.paste(im, (S + i * (FW * S + S), S), im)
        big.save(os.path.join(preview_dir, 'monia_dirs_x8.png'))
        # GIF über alle 32 Frames
        gif = []
        for f in range(NF):
            fr = Image.new('RGBA', (4 * (FW * 5 + 5) + 5, FH * 5 + 10), GREEN)
            for i, d in enumerate(ORDER):
                im = rows[d][f].resize((FW * 5, FH * 5), Image.NEAREST)
                fr.paste(im, (5 + i * (FW * 5 + 5), 5), im)
            gif.append(fr.convert('P', palette=Image.ADAPTIVE))
        gif[0].save(os.path.join(preview_dir, 'monia_dirs.gif'), save_all=True,
                    append_images=gif[1:], duration=70, loop=0, disposal=2)
    print('ok', sheet.size)

if __name__ == '__main__':
    main()
