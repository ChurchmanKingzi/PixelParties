def grid(rows):
    """Text-Map → Liste von Zeilen; prüft Breite 24 und Höhe 32."""
    rows = [r for r in rows.strip('\n').split('\n')]
    assert len(rows) == FH, f'{len(rows)} Zeilen statt {FH}'
    for i, r in enumerate(rows):
        assert len(r) == FW, f'Zeile {i} hat {len(r)} Zeichen: {r!r}'
    return [list(r) for r in rows]

