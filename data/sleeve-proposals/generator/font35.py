def text35(cv,s,x,y,c,scale=1,center=False,spacing=1,shadow=None):
    s=s.upper()
    w=len(s)*(3+spacing)*scale-spacing*scale
    if center: x-=w//2
    for i,ch in enumerate(s):
        g=G.get(ch,G['?'])
        for yy,row in enumerate(g):
            for xx,v in enumerate(row):
                if v=='#':
                    for sy in range(scale):
                        for sx in range(scale):
                            X=x+i*(3+spacing)*scale+xx*scale+sx; Y=y+yy*scale+sy
                            if shadow: cv.px(X+shadow[0],Y+shadow[1],shadow[2])
                            cv.px(X,Y,c)
    return w
def width35(s,scale=1,spacing=1): return len(s)*(3+spacing)*scale-spacing*scale
