    # Umlaute und ß
    G['ä'] = (['.#.#.', '.....'] + G['a'][0], 2)
    G['ö'] = (['.#.#.', '.....'] + G['o'][0], 2)
    G['ü'] = (['.#.#.', '.....'] + G['u'][0], 2)
